// @vitest-environment node
import { describe, it, expect } from "vitest";
import { scanSensitive } from "./sensitive";

/**
 * 실제 중고거래 대화에서 나올 법한 문장 모음.
 *
 * 이 기능은 **틀린 번호를 잡는 것이 못 잡는 것보다 나쁘다** — 감지한 번호로 사기 이력을
 * 조회해 주기 때문에, 엉뚱한 숫자가 섞이면 "신고된 적 없어요"라는 거짓 안심을 준다.
 * 그래서 잡는 경우마다 digits까지 정확히 확인한다.
 */

function digitsOf(text: string): string[] {
  return scanSensitive(text).spans.map((s) => `${s.kind}:${s.digits}`);
}

describe("번호를 정확히 잡아낸다", () => {
  const cases: [string, string[]][] = [
    ["010-1234-5678 로 연락주세요", ["phone:01012345678"]],
    ["제 번호 010-1234-5678 15000원에 드릴게요", ["phone:01012345678"]],
    ["010-1234-5678 30000원 입금하시면 됩니다", ["phone:01012345678"]],
    ["010 1234 5678 로 전화주세요", ["phone:01012345678"]],
    ["010*1234*5678", ["phone:01012345678"]],
    ["010\n1234\n5678", ["phone:01012345678"]],
    ["번호010-1234-5678입니다", ["phone:01012345678"]],
    ["+82 10 1234 5678 로 연락주세요", ["phone:821012345678"]],
    ["국민은행 110-234-567890 15000", ["account:110234567890"]],
    ["계좌 110-234-567890 15000원 보내주세요", ["account:110234567890"]],
    ["농협 3521045678901234 12000원 입금해주세요", ["account:3521045678901234"]],
    ["010-1234-5678 ** 3333011234567", ["phone:01012345678", "account:3333011234567"]],
    ["영1영-5O14-6@977", ["phone:01050146977"]],
    ["공일공 삼2사5 육칠팔구", ["phone:01032456789"]],
    ["010 1234 5678 010 8765 4321 둘 다 돼요", ["phone:01012345678", "phone:01087654321"]],
    // 하이픈 양옆을 띄어 쓰는 표기
    ["010 - 1234 - 5678 입니다", ["phone:01012345678"]],
    ["번호는 010 / 1234 / 5678", ["phone:01012345678"]],
    ["국민은행 3333 - 01 - 1234567", ["account:3333011234567"]],
    // 택배 이야기와 계좌가 한 메시지에 있는, 가장 흔한 사기 문장
    ["택배로 보낼게요 국민은행 110-234-567890 으로 입금해주세요", ["account:110234567890"]],
    ["선입금해주시면 택배 보내드려요 농협 302-1234-5678-91", ["account:3021234567891"]],
    // 알파벳 우회 표기
    ["O1O-1234-5678", ["phone:01012345678"]],
    ["OIO-1234-5678", ["phone:01012345678"]],
    // 한글 수사 뒤에 조사가 붙은 경우 — 조사는 번호에 넣지 않는다
    ["공일공일이삼사오육칠팔이에요", ["phone:01012345678"]],
    // 장식 기호·쉼표·이모지로 나눠 적은 번호
    ["★010★9876★5432★ 연락주세요", ["phone:01098765432"]],
    ["제 번호에요 010,1234,5678", ["phone:01012345678"]],
    ["010-1234📞5678", ["phone:01012345678"]],
  ];

  it.each(cases)("%s", (text, expected) => {
    expect(digitsOf(text)).toEqual(expected);
  });
});

describe("번호가 아닌 것은 건드리지 않는다", () => {
  const cases = [
    "15000 13000 어떠세요",
    "18000 15000 까지 되나요",
    "20,000 15,000 로 해주세요",
    "45000 40000 35000 30000",
    "가격표 10000 20000 30000 40000 50000",
    "가격 15,000원에 팔아요",
    "내일 3시에 잠실역 2번 출구에서 봬요",
    "2026-07-25 18:00 에 만나요",
    "10:00 12:00 14:00 중에",
    "2019 2020 2021 연식 다 있어요",
    "그램 17 i5 16GB 512GB 팔아요",
    "i7 16GB 256GB 노트북",
    "RTX 4070 Ti 12GB 그래픽카드",
    "우리 집 앞으로 와주세요",
    "하나 더 사면 얼마인가요",
    "가격은 15000 25000 사이에서 조율해요",
    "5678이에요",
    "1만원에 드려요",
    "치수 1200 1500 1800 2000 2200",
    "500 1000 2000 3000 5000 10000 단위",
    "제품 2개 각 12000 20000 원",
    // 가격 범위 — 물결·하이픈·쉼표로 이어 써도 번호가 아니다
    "30000~40000 사이면 살게요",
    "15000-20000원에 팔아요",
    "25000,20000 중에 고르세요",
    "12000~15000 어떠세요",
    // 은행 이야기 중에 나오는 날짜·금액
    "계좌이체로 2026.07.24 에 입금할게요",
    "은행 문 닫기 전 2026-07-24 까지요",
    "국민은행으로 12,000,000원 보내드릴게요",
    // 은행 이야기 중의 가격 흥정 — 띄어 쓴 숫자를 계좌로 합치지 않는다
    "계좌로 보내주시면 돼요 15000 13000 중에 어떠세요",
    "계좌이체 하면 얼마예요? 25000 20000 정도 생각했어요",
    "토스로 보낼게요 20000 30000 중에 얼마 드릴까요",
    "은행 갈 일 있어서요 45000 40000 어떠세요",
    "계좌 알려주세요 10:00 12:00 14:00 중에",
    // 숫자를 늘어놓은 것 — 가격 사다리, 사이즈 표
    "10000-13000-15000 중 골라주세요",
    "치수 별로 90-95-100-105-110 있어요",
    "사이즈 230-235-240-245-250 다 있어요",
  ];

  it.each(cases)("%s", (text) => {
    expect(digitsOf(text)).toEqual([]);
  });
});

describe("우회 표기 여부를 구분한다", () => {
  it("그대로 쓴 번호는 우회로 보지 않는다", () => {
    expect(scanSensitive("010-1234-5678").hasEvasive).toBe(false);
  });

  it("한글·알파벳으로 바꿔 쓴 번호는 우회로 본다", () => {
    expect(scanSensitive("영1영-5O14-6@977").hasEvasive).toBe(true);
    expect(scanSensitive("공일공 삼2사5 육칠팔구").hasEvasive).toBe(true);
  });

  it("상품 사양은 우회 표기로 오해하지 않는다", () => {
    expect(scanSensitive("그램 17 i5 16GB 512GB 팔아요").hasEvasive).toBe(false);
  });
});
